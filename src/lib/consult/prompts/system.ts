export function buildConsultUserPrompt(messages: ConsultMessage[]): string {
  const history = messages
    .map((m) => `${m.role === "user" ? "ユーザー" : "アシスタント"}: ${m.content}`)
    .join("\n\n");

  return [
    "【会話履歴】",
    history,
    "",
    "最新のユーザー発言に対し、会話を1段階前に進める短い返答をしてください。",
    "今回の発言から得られた新情報を使い、既知条件を繰り返さないでください。",
    "未確定事項を聞く場合は open question にせず、2〜3個の具体的な選択肢を提示してください。",
    "質問で終わらせる必要はありません。追加質問が不要なら提案のみで終えてください。",
  ].join("\n");
}
